import assert from 'node:assert/strict';
import { createGame } from '../game/src/sim/sim.js';
import { commandSite } from '../game/src/sim/coach.js';
const state = createGame(14), team = state.teams[state.player.team];
assert.equal(commandSite(state, 'B'), true);
assert.equal(team.plan.site, 'B');
const bots = state.actors.filter(a => a.isBot && a.team === team.id);
assert.ok(bots.filter(a => a.brain.site === 'B').length >= 3);
assert.ok(new Set(bots.filter(a => !a.brain.lurk).map(a => a.brain.route)).size === 2);
assert.equal(commandSite(state, 'A'), false, 'cooldown');
state.time += 5;
assert.equal(commandSite(state, 'A'), true);
state.time += 5; state.core.state = 'planted';
assert.equal(commandSite(state, 'B'), false, 'cannot cancel planted objective');
state.core.state = 'carried'; state.player.alive = false;
assert.equal(commandSite(state, 'B'), false, 'dead players cannot order');
state.player.alive = true; team.side = 1;
assert.equal(commandSite(state, 'B'), true);
assert.ok(bots.every(a => a.brain.site === 'B' && a.brain.plan === 'hold'));
assert.equal(team.plan.rotated, true);
state.time += 5;
assert.equal(commandSite(state, 'C'), false, 'invalid site');
state.round.phase = 'over';
assert.equal(commandSite(state, 'A'), false, 'round finished');
console.log('PASS: attack split routes, retarget, cooldown, objective/death guards and defence rotation');
